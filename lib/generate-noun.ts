// Generates a plugin's `$.<noun>` contract and wrapper from its qsm.json.

import { basename } from "node:path";
import {
  type CommandArg,
  parseManifest,
  type QsmManifest,
  toCamel,
  toKebab,
  verbsOf,
} from "./qsm-manifest.ts";

export type { CommandArg, CommandDecl, QsmManifest } from "./qsm-manifest.ts";

interface ParsedVerb {
  readonly verb: string;
  readonly method: string;
  readonly args: readonly CommandArg[];
  readonly passthrough: boolean;
}

/** The plugin's own contract, as the generated wrapper imports it. Kept apart
 * from the template so the import gate never reads a string as an import. */
const CONTRACT = "../types/index.d.ts";

function parseVerbs(manifest: QsmManifest): ParsedVerb[] {
  const [binName] = Object.keys(manifest.qsm.bin ?? {});
  const verbs: ParsedVerb[] = [];
  for (const [verb, decl] of verbsOf(manifest, binName ?? "")) {
    // A verb that is no data call (a long-running server, a passthrough) is
    // marked `noNoun` in qsm.json: the wrapper always appends `--json`, so it
    // would be generated as a method that can only throw.
    if (decl.noNoun === true) {
      continue;
    }
    const args = (decl.args ?? []).filter((a) => a.name !== "json");
    const method = toCamel(verb.replaceAll(" ", "-"));
    verbs.push({ verb, method, args, passthrough: decl.passthrough === true });
  }
  return verbs;
}

/** The engine takes a noun only as a flat object of methods (`$.usage.toon`
 * as an object is refused: "an interface is an object of methods"), so a
 * verb's words join into one method: `toon encode` is `toonEncode`. Two
 * verbs that join to one name are refused. */
function flatMethods(verbs: readonly ParsedVerb[], render: (v: ParsedVerb) => string): string {
  const seen = new Map<string, string>();
  for (const v of verbs) {
    const other = seen.get(v.method);
    if (other !== undefined) {
      throw new Error(`qsm.json: "${other}" and "${v.verb}" both become the method ${v.method}`);
    }
    seen.set(v.method, v.verb);
  }
  return verbs.map(render).join("\n");
}

function pascalCase(noun: string): string {
  return noun.charAt(0).toUpperCase() + noun.slice(1);
}

function tsTypeOf(a: CommandArg): string {
  const base =
    a.choices === undefined ? a.type : a.choices.map((c) => JSON.stringify(c)).join(" | ");
  return a.repeatable === true ? `(${base})[]` : base;
}

function optionsTypeOf(v: ParsedVerb): string {
  const fields = v.args.map(
    (a) => `    ${a.name}${a.required === true ? "" : "?"}: ${tsTypeOf(a)};`,
  );
  if (v.passthrough) {
    fields.push("    rest?: string[];");
  }
  if (fields.length === 0) {
    return "";
  }
  return `{\n${fields.join("\n")}\n  }`;
}

/** The noun contract, `types/index.d.ts`: one method per verb, its options
 * object typed from `args`, returning `Promise<unknown>` for now (the
 * binary's own JSON shapes are not yet fed back through generate-noun). */
export function generateTypes(manifest: QsmManifest, noun: string): string {
  const pascal = pascalCase(noun);
  const verbs = parseVerbs(manifest);
  const methods = flatMethods(verbs, (v) => {
    const optionsType = optionsTypeOf(v);
    const param = optionsType === "" ? "" : `options: ${optionsType}`;
    return `  ${v.method}(${param}): Promise<unknown>;`;
  });
  return `// Generated by lib/generate-noun.ts from qsm.json. Do not hand-edit; run
// \`bun lib/generate-noun.ts plugins/<name>\` again after changing qsm.json.

export type ${pascal} = {
${methods}
};

declare module 'claude-code' {
  interface EngineInterface {
    ${noun}: ${pascal};
  }
}
`;
}

/** One verb's table row: the command words and how each option becomes argv.
 * `flag` is null for a positional argument; `boolean` flags take no value. */
function verbRow(v: ParsedVerb, bin: string): string {
  const words = [bin, ...v.verb.split(" ")];
  const args = v.args.map((a) => {
    const fields = [
      `name: ${JSON.stringify(a.name)}`,
      `flag: ${a.positional === true ? "null" : JSON.stringify(`--${toKebab(a.name)}`)}`,
      ...(a.type === "boolean" && a.positional !== true ? ["boolean: true"] : []),
    ];
    return `{ ${fields.join(", ")} }`;
  });
  const restFlag = v.passthrough ? ", passthrough: true" : "";
  return `  ${v.method}: { words: ${JSON.stringify(words)}, args: [${args.join(", ")}]${restFlag} },`;
}

/** The noun's wrapper, `hooks/noun.generated.ts`: a table with one row per
 * verb, one `argvOf` that turns a row and the caller's options into argv,
 * and `registerNoun(on)`, whose `engine.create` hook turns every row into a
 * method on a flat noun. A new verb is a new row, never a new function, so
 * the file's shape does not grow with the verbs. Imported by the plugin's own
 * hooks module, never by another plugin, which reaches it through
 * `$.<noun>`; method types come from the plugin's own `types/index.d.ts`.
 *
 * `beneath` (`engine.create`'s own `next(e)`) is only ever read through its
 * own property chain inside the hook, never passed to a function:
 * `claude plugin validate` refuses a hooks module that passes it ("the value
 * of next(e) at engine.create is passed as an argument"). */
export function generateHooks(manifest: QsmManifest, noun: string, bin: string): string {
  const verbs = parseVerbs(manifest);
  const rows = flatMethods(verbs, (v) => verbRow(v, bin));
  const pascal = pascalCase(noun);
  return `// Generated by lib/generate-noun.ts from qsm.json. Do not hand-edit; run
// \`bun lib/generate-noun.ts plugins/<name>\` again after changing qsm.json.
import type { On } from "claude-code";
import type { ${pascal} } from "${CONTRACT}";

/** How one option becomes argv: a positional value (\`flag\` null), a bare
 * boolean flag, or a flag and its value; a list repeats it per element. */
export interface VerbArg {
  readonly name: string;
  readonly flag: string | null;
  readonly boolean?: true;
}

export interface VerbRow {
  readonly words: readonly string[];
  readonly args: readonly VerbArg[];
  readonly passthrough?: true;
}

export const verbs: Readonly<Record<string, VerbRow>> = {
${rows}
};

/** One verb's argv: its words, each option in declaration order, the
 * passthrough rest after \`--\`, and \`--json\` last. */
export function argvOf(row: VerbRow, options: Readonly<Record<string, unknown>> = {}): string[] {
  const argv = [...row.words];
  for (const arg of row.args) {
    const value = options[arg.name];
    const values = Array.isArray(value) ? value : [value];
    for (const one of values) {
      if (one === undefined || one === false) {
        continue;
      }
      argv.push(...(arg.flag === null ? [] : [arg.flag]), ...(arg.boolean ? [] : [String(one)]));
    }
  }
  const rest = options.rest;
  if (row.passthrough && Array.isArray(rest)) {
    argv.push("--", ...rest.map(String));
  }
  argv.push("--json");
  return argv;
}

/** The binary prints one outcome envelope on stdout under --json:
 * { code, exit, reason, message, warnings, data }. Data on ok; otherwise the
 * code and message become the error. A stale or misbehaving binary that
 * prints something else (not JSON, or JSON with no numeric \`exit\`) throws
 * loud here instead of a raw JSON.parse SyntaxError or a silent \`undefined\`. */
export function unwrap(
  argv: readonly string[],
  result: { readonly exitCode: number; readonly stdout: string; readonly stderr: string },
  label = argv.slice(0, 2).join(" "),
): unknown {
  const text = result.stdout.trim();
  const stderr = result.stderr.trim().slice(0, 200);
  const cause = \`(exit \${result.exitCode}): \${stderr.length > 0 ? stderr : "no stderr"}\`;
  if (text.length === 0) {
    throw new Error(\`\${argv.join(" ")}: printed no envelope \${cause}\`);
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch {
    parsed = undefined;
  }
  if (typeof parsed !== "object" || parsed === null || typeof (parsed as { exit?: unknown }).exit !== "number") {
    throw new Error(\`\${argv.join(" ")}: stdout is not an outcome envelope \${cause}: \${text.slice(0, 200)}\`);
  }
  const envelope = parsed as { code: string; exit: number; message: string; data: unknown };
  if (envelope.exit !== 0) {
    throw new Error(\`\${label}: \${envelope.code}: \${envelope.message}\`);
  }
  return envelope.data;
}

/** Adds $.${noun} to the engine. Call once from the plugin's own
 * \`register(on, options)\` — never call the engine.create hook's own
 * \`next(e)\` result from anywhere but here. */
export function registerNoun(on: On): void {
  on("engine.create", async (_$, e, next) => {
    const beneath = await next(e);
    const run = async (row: VerbRow, options?: Readonly<Record<string, unknown>>): Promise<unknown> => {
      const argv = argvOf(row, options);
      let result: Awaited<ReturnType<typeof beneath.process.run>>;
      try {
        result = await beneath.process.run(argv);
      } catch (error) {
        // A spawn in a deleted directory fails as ENOENT naming the binary; name the directory. A
        // check that cannot run leaves the spawn's own error as the cause.
        const gone = await beneath.session
          .cwd()
          .then(async (cwd) => ((await beneath.fs.exists(cwd)) ? null : cwd))
          .catch(() => null);
        if (gone !== null) {
          throw new Error(\`\${row.words.join(" ")}: the session's working directory \${gone} no longer exists; cd to one that does\`);
        }
        throw error;
      }
      return unwrap(argv, result, row.words.join(" "));
    };
    const methods = Object.entries(verbs).map(([method, row]) => [
      method,
      (options?: Readonly<Record<string, unknown>>) => run(row, options),
    ]);
    return { ...beneath, ${noun}: Object.fromEntries(methods) as ${pascal} };
  });
}
`;
}

export interface GenerateResult {
  readonly typesPath: string;
  readonly typesContent: string;
  readonly hooksPath: string;
  readonly hooksContent: string;
}

/** Pure: reads nothing, writes nothing. `pluginDir` names the plugin's own
 * directory (its basename is only used for error messages). */
export function generateNoun(manifest: QsmManifest, pluginDir: string): GenerateResult {
  const { noun } = manifest.qsm;
  if (noun === undefined || noun.length === 0) {
    throw new Error(`${basename(pluginDir)}/qsm.json: qsm.noun is required to generate a noun`);
  }
  const [binName] = Object.keys(manifest.qsm.bin ?? {});
  if (binName === undefined) {
    throw new Error(`${basename(pluginDir)}/qsm.json: qsm.bin is required to generate a noun`);
  }
  return {
    typesPath: `${pluginDir}/types/index.d.ts`,
    typesContent: generateTypes(manifest, noun),
    hooksPath: `${pluginDir}/hooks/noun.generated.ts`,
    hooksContent: generateHooks(manifest, noun, binName),
  };
}

export interface CheckResult {
  readonly stale: readonly string[];
}

/** Compares the committed files with a fresh generation; writes nothing. */
export function checkNoun(
  manifest: QsmManifest,
  pluginDir: string,
  readFile: (path: string) => string | null,
): CheckResult {
  const result = generateNoun(manifest, pluginDir);
  const stale = (
    [
      [result.typesPath, result.typesContent],
      [result.hooksPath, result.hooksContent],
    ] as const
  )
    .filter(([path, content]) => readFile(path) !== content)
    .map(([path]) => path);
  return { stale };
}

/** plugins/<name> for every staged plugins/<name>/qsm.json, once each. */
export function stagedPluginDirs(stagedPaths: readonly string[]): string[] {
  const dirs = stagedPaths
    .map((p) => /^(plugins\/[^/]+)\/qsm\.json$/.exec(p)?.[1])
    .filter((d): d is string => d !== undefined);
  return [...new Set(dirs)];
}

async function git(gitArgs: string[]): Promise<string> {
  const { spawnSync } = await import("node:child_process");
  const run = spawnSync("git", gitArgs, { encoding: "utf8" });
  if (run.status !== 0) {
    throw new Error(`git ${gitArgs.join(" ")}: ${run.stderr.trim()}`);
  }
  return run.stdout;
}

async function writeNoun(result: GenerateResult, stage: boolean): Promise<void> {
  const { mkdirSync, writeFileSync } = await import("node:fs");
  const { dirname } = await import("node:path");
  for (const [path, content] of [
    [result.typesPath, result.typesContent],
    [result.hooksPath, result.hooksContent],
  ] as const) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    if (stage) {
      await git(["add", path]);
    }
    process.stdout.write(`wrote ${path}\n`);
  }
}

/** The pre-commit step: regenerate from the staged qsm.json, so a partly
 * staged edit commits the contract that matches what is committed. A plugin
 * with no bin or no noun is skipped; the generated gate names what is missing. */
async function regenerateStaged(): Promise<void> {
  const { resolve } = await import("node:path");
  const staged = (await git(["diff", "--cached", "--name-only", "--diff-filter=ACMR"])).split("\n");
  for (const dir of stagedPluginDirs(staged)) {
    const manifest = parseManifest(JSON.parse(await git(["show", `:${dir}/qsm.json`])));
    const hasBin = Object.keys(manifest.qsm.bin ?? {}).length > 0;
    if (hasBin && manifest.qsm.noun !== undefined) {
      await writeNoun(generateNoun(manifest, resolve(dir)), true);
    }
  }
}

async function regenerateOne(pluginDir: string, check: boolean): Promise<number> {
  const { existsSync, readFileSync } = await import("node:fs");
  const { resolve } = await import("node:path");
  const dir = resolve(pluginDir);
  const manifest = parseManifest(JSON.parse(readFileSync(resolve(dir, "qsm.json"), "utf8")));
  if (!check) {
    await writeNoun(generateNoun(manifest, dir), false);
    return 0;
  }
  const { stale } = checkNoun(manifest, dir, (p) =>
    existsSync(p) ? readFileSync(p, "utf8") : null,
  );
  for (const p of stale) {
    process.stderr.write(`stale: ${p}\n`);
  }
  return stale.length === 0 ? 0 : 1;
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const pluginDir = args.find((a) => !a.startsWith("--"));
  if (args.includes("--staged")) {
    await regenerateStaged();
  } else if (pluginDir === undefined) {
    process.stderr.write("usage: bun lib/generate-noun.ts <plugin-dir> [--check] | --staged\n");
    process.exit(2);
  } else {
    process.exit(await regenerateOne(pluginDir, args.includes("--check")));
  }
}
