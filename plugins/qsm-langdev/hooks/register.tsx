// qsm-langdev's function-hooks module: the Bash guard, and the edit hook that tells the model what
// an edit did to the file's findings. The guard's rule is lib/blocked-git.ts, the findings are the
// `edited` verb's. The stop gate (hooks.json, dist/gate-hook) stays a classic command hook: its
// event is SubagentStop, which has no function form, and a function hook cannot block a stop.
import type { Caught, EngineInterface, On } from "claude-code";
import { gitDecision } from "../lib/blocked-git.ts";
import { registerNoun } from "./noun.generated.ts";

const EDIT_TOOLS: readonly string[] = ["Write", "Edit", "NotebookEdit"];

/** What every `.catch` here does first: a toast and a log for the person. */
function failed($: EngineInterface, event: string, error: Caught["error"]): string {
  const said = error.message ?? error.kind;
  $.ui.toast(`qsm-langdev ERROR: ${event}: ${said.slice(0, 120)}`);
  $.ui.log(`${event} failed (${error.kind})`);
  return said;
}

/** The `text` of the edited verb's data; null when it had nothing to say. */
function findingsText(data: unknown): string | null {
  const text = typeof data === "object" && data !== null ? Reflect.get(data, "text") : null;
  return typeof text === "string" && text.length > 0 ? text : null;
}

/** A commit or push that skips the git hooks is refused; `QSM_LANGDEV_ALLOW` goes to the person.
 * The guard fails closed. */
function registerGuard(on: On): void {
  on("tool.call", { tool: "Bash" }, (_$, e, next) => {
    const answer = e.tool === "Bash" ? gitDecision(e.command) : null;
    return answer?.decision === "deny" ? { deny: answer.reason } : next(e);
  }).catch(($, _e, next) => ({
    deny: `qsm-langdev guard failed: ${failed($, "tool.call", next.error)}`,
  }));

  on("tool.check", { tool: "Bash" }, (_$, e, next) => {
    const command = (e.input as { command?: unknown } | null)?.command;
    const answer = typeof command === "string" ? gitDecision(command) : null;
    return answer?.decision === "ask" ? { decision: "ask", reason: answer.reason } : next(e);
  }).catch(($, _e, next) => ({
    decision: "deny",
    reason: `qsm-langdev guard failed: ${failed($, "tool.check", next.error)}`,
  }));
}

/** After a Write, Edit or NotebookEdit ran, the file's findings against HEAD go to the model as the
 * result's context. Advisory: a failure leaves the result as the tool made it. */
function registerEditFindings(on: On): void {
  on("tool.call", async ($, e, next) => {
    const result = await next(e);
    if (result.deny !== undefined || result.isError === true || !EDIT_TOOLS.includes(e.tool)) {
      return result;
    }
    const file = Reflect.get(e, "file_path") ?? Reflect.get(e, "notebook_path");
    if (typeof file !== "string") {
      return result;
    }
    const text = findingsText(
      await $.langdev.edited({ file, session: await $.session.id(), agent: e.agentId }),
    );
    return text === null ? result : { ...result, context: [...(result.context ?? []), text] };
  }).catch(($, e, next) => {
    const said = failed($, "tool.call", next.error);
    $.ui.log(`the result goes on without findings (${said})`);
    return next(e);
  });
}

export function register(on: On): void {
  // Adds $.langdev: one method per qsm-langdev verb, generated by
  // lib/generate-noun.ts. Never hand-edit noun.generated.ts or types/index.d.ts.
  registerNoun(on);
  registerGuard(on);
  registerEditFindings(on);
}
