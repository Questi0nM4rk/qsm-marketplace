#!/usr/bin/env bun
// Regenerates lib/rules-data.ts from rules/*.yaml. Run this after adding,
// removing, or editing a rules file: the compiled CLI binary never reads that
// directory at run time, only the generated module.

import { spawnSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const PLUGIN_ROOT = join(import.meta.dir, "..");
const RULES_ROOT = join(PLUGIN_ROOT, "rules");
const OUT_FILE = join(PLUGIN_ROOT, "lib", "rules-data.ts");

const RULES_SUFFIX = ".yaml";

/** Each `<language>.yaml` under `rulesRoot` by its language, sorted so the
 * same files regenerate the same module on every machine. A file holding no
 * rule is refused: semgrep handed an empty config runs nothing and says
 * nothing, which reads as a clean file. */
export function readOwnRules(rulesRoot: string): Record<string, string> {
  const rules: Record<string, string> = {};
  for (const file of readdirSync(rulesRoot).sort()) {
    if (!file.endsWith(RULES_SUFFIX)) {
      continue;
    }
    const text = readFileSync(join(rulesRoot, file), "utf8");
    if (!/^\s*- id: \S/m.test(text)) {
      throw new Error(`rules/${file} holds no rule`);
    }
    rules[file.slice(0, -RULES_SUFFIX.length)] = text;
  }
  return rules;
}

function main(): void {
  const header =
    "// Generated by scripts/generate-rules-data.ts from rules/*.yaml. Do not edit by\n" +
    "// hand: it is what the compiled binary reads instead of that directory, so it\n" +
    "// needs no marketplace checkout at run time.\n\n";
  const body = `export const OWN_RULES: Readonly<Record<string, string>> = ${JSON.stringify(
    readOwnRules(RULES_ROOT),
    null,
    2,
  )};\n`;

  writeFileSync(OUT_FILE, header + body);

  // Formatted here, so a regenerate is never a lint failure.
  const formatted = spawnSync("bunx", ["oxfmt", OUT_FILE], {
    stdio: ["ignore", "ignore", "inherit"],
  });
  if (formatted.status !== 0) {
    console.error(`wrote ${OUT_FILE} but oxfmt could not format it`);
    process.exit(1);
  }
  console.log(`wrote ${OUT_FILE}`);
}

// Imported by the drift test for readOwnRules alone; only a run writes.
if (import.meta.main) {
  main();
}
