#!/usr/bin/env bun
// Regenerates lib/profiles-data.ts from profiles/**. Run this after adding,
// removing, or editing any file under profiles/ — the compiled CLI binary
// never reads that directory at run time, only the generated module.

import { spawnSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

const PLUGIN_ROOT = join(import.meta.dir, "..");
const PROFILES_ROOT = join(PLUGIN_ROOT, "profiles");
const OUT_FILE = join(PLUGIN_ROOT, "lib", "profiles-data.ts");

const TEMPLATE_SUFFIX = ".template";

function byName(a: { name: string }, b: { name: string }): number {
  return a.name.localeCompare(b.name);
}
function scaffoldedName(name: string): string {
  return name.endsWith(TEMPLATE_SUFFIX) ? name.slice(0, -TEMPLATE_SUFFIX.length) : name;
}

interface Entry {
  file: string;
  content: string;
}

// Sorted, because readdir order is the filesystem's: unsorted, the same
// profiles regenerate in a different order on another machine.
function subdirectories(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .toSorted();
}

/** One language directory's files, keyed by the language and its targets. */
function readLanguage(language: string, languageDir: string, into: Record<string, Entry[]>): void {
  // A directory inside a language directory names a target: what the code
  // runs on, which is a different question from how strict the profile is.
  // `ts/` is the language's default target and `ts/browser/` carries only
  // the files that differ, so nothing is duplicated to stay in sync by hand.
  for (const source of readdirSync(languageDir, { withFileTypes: true }).toSorted(byName)) {
    const key = source.isDirectory() ? `${language}@${source.name}` : language;
    const from = source.isDirectory()
      ? readdirSync(join(languageDir, source.name))
          .toSorted()
          .map((file) => join(source.name, file))
      : [source.name];
    const entries = into[key] ?? [];
    for (const rel of from) {
      entries.push({
        file: scaffoldedName(basename(rel)),
        content: readFileSync(join(languageDir, rel), "utf8"),
      });
    }
    into[key] = entries;
  }
}

/** What lib/profiles-data.ts holds for the profiles under `profilesRoot`. */
export function readProfiles(profilesRoot: string): Record<string, Record<string, Entry[]>> {
  const data: Record<string, Record<string, Entry[]>> = {};
  for (const profile of subdirectories(profilesRoot)) {
    const languages: Record<string, Entry[]> = {};
    const profileDir = join(profilesRoot, profile);
    for (const language of subdirectories(profileDir)) {
      readLanguage(language, join(profileDir, language), languages);
    }
    data[profile] = languages;
  }
  return data;
}

function main(): void {
  const header =
    "// Generated by scripts/generate-profiles-data.ts from profiles/**. Do not edit by\n" +
    "// hand — it is what the compiled binary reads instead of that directory, so it\n" +
    "// needs no marketplace checkout at run time.\n\n";
  const body = `export const PROFILE_DATA: Readonly<
  Record<string, Readonly<Record<string, readonly { file: string; content: string }[]>>>
> = ${JSON.stringify(readProfiles(PROFILES_ROOT), null, 2)} as const;\n`;

  writeFileSync(OUT_FILE, header + body);

  // JSON.stringify quotes every key and lays strings out its own way, which is
  // not what this repository's formatter prints. Formatting here rather than
  // leaving it to the next person means a regenerate is never a lint failure.
  const formatted = spawnSync("bunx", ["oxfmt", OUT_FILE], {
    stdio: ["ignore", "ignore", "inherit"],
  });
  if (formatted.status !== 0) {
    console.error(`wrote ${OUT_FILE} but oxfmt could not format it`);
    process.exit(1);
  }
  console.log(`wrote ${OUT_FILE}`);
}

// Imported by the drift test for readProfiles alone; only a run writes.
if (import.meta.main) {
  main();
}
