// qsm-builder's function-hooks module: the noun, the manifest check at the moment a manifest is
// written, and the open tasks of a plugin told to the agent the first time it touches its files.
import type { On } from "claude-code";
import { isRecord } from "../lib/guards.ts";
import { pluginOfPath } from "../lib/brief-path.ts";
import { applyEdit, checkManifest, denial, isManifestPath } from "../lib/manifest-check.ts";
import { registerNoun } from "./noun.generated.ts";
import { registerView } from "./view.tsx";

/** The plugins already told about, per session and marketplace: `<session>:<root>:<plugin>`. */
const told = new Set<string>();

/** The `text` of the brief verb's data: a string, or null when there is nothing to tell. */
function briefText(data: unknown): string | null {
  return isRecord(data) && typeof data.text === "string" ? data.text : null;
}

function registerBrief(on: On): void {
  // The first Read, Write or Edit of a file of a plugin in this session adds that plugin's open
  // lens edits and feedback to what the model reads after the result, once per plugin. A
  // failure toasts and logs its cause and leaves the result as the tool made it.
  on("tool.call", { tool: ["Read", "Write", "Edit"] }, async ($, e, next) => {
    const result = await next(e);
    const where = pluginOfPath(e.file_path);
    if (result.deny !== undefined || result.isError === true || where === null) {
      return result;
    }
    const key = `${await $.session.id()}:${where.root}:${where.plugin}`;
    if (told.has(key)) {
      return result;
    }
    told.add(key);
    const text = briefText(await $.builder.lensBrief({ file: e.file_path }));
    return text === null ? result : { ...result, context: [...(result.context ?? []), text] };
  }).catch(($, e, next) => {
    const cause =
      next.error.message ?? `${next.error.kind}: ran past its ${next.error.budget} ms budget`;
    $.ui.toast(`qsm-builder ERROR: tool.call: ${cause.slice(0, 240)}`);
    $.ui.log(
      `the open tasks of a plugin were not added to ${e.file_path} (${next.error.kind}): ${cause}`,
    );
    return next(e);
  });
}

function registerManifestCheck(on: On): void {
  // Refuses a Write of a plugin.json that breaks the manifest rules, before the file lands.
  on("tool.call", { tool: "Write" }, (_$, e, next) => {
    if (!isManifestPath(e.file_path)) {
      return next(e);
    }
    const found = checkManifest(e.content);
    return found.length === 0 ? next(e) : { deny: denial(e.file_path, found) };
  }).catch(($, e, next) => {
    const reason = `${next.error.kind}${next.error.message === undefined ? "" : `: ${next.error.message.slice(0, 120)}`}`;
    $.ui.toast(`qsm-builder ERROR: tool.call: ${reason}`);
    $.ui.log(`the manifest check on Write failed (${next.error.kind})`);
    return next(e);
  });

  // Refuses an Edit whose result would be a plugin.json that breaks the manifest rules.
  on("tool.call", { tool: "Edit" }, async ($, e, next) => {
    if (!isManifestPath(e.file_path)) {
      return next(e);
    }
    // A manifest the edit names but cannot be read is not this hook's to
    // report: the tool's own error says it better.
    let current: string;
    try {
      current = await $.fs.read(e.file_path);
    } catch {
      return next(e);
    }
    const after = applyEdit(current, e.old_string, e.new_string, e.replace_all ?? false);
    if (after === null) {
      return next(e);
    }
    const found = checkManifest(after);
    return found.length === 0 ? next(e) : { deny: denial(e.file_path, found) };
  }).catch(($, e, next) => {
    const reason = `${next.error.kind}${next.error.message === undefined ? "" : `: ${next.error.message.slice(0, 120)}`}`;
    $.ui.toast(`qsm-builder ERROR: tool.call: ${reason}`);
    $.ui.log(`the manifest check on Edit failed (${next.error.kind})`);
    return next(e);
  });
}

export function register(on: On): void {
  // Adds $.builder: one method per qsm-builder verb, generated by
  // lib/generate-noun.ts. Never hand-edit noun.generated.ts or types/index.d.ts.
  registerNoun(on);
  registerBrief(on);
  registerManifestCheck(on);
  registerView(on);
}
