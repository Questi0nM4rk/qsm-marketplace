// qsm-memory's function-hooks module: the noun, and the native events that call its verbs. Every
// rule is the verb's (lib/); the saves detach inside the verb, so the session-end chain's 1.5 s
// covers only starting one.
import type { Caught, EngineInterface, On } from "claude-code";
import { registerNoun } from "./noun.generated.ts";

/** Whether the next prompt is owed the briefing: a session start and a /clear set it, the first
 * prompt after clears it. The engine has no hidden-context event at those moments. */
let briefingOwed = false;

/** The compaction summary the last briefing followed; a newer one means a compaction removed it. */
let briefedSummary: string | undefined;

const SUMMARY_OPENING = "This session is being continued from a previous conversation";

/** The newest compaction summary among the conversation's rows. `session.compact` and the
 * `compact_boundary` notice never reach a plugin the organization's policy module runs ahead of,
 * so a compaction is read from the rows the next prompt can see. */
async function latestSummary($: EngineInterface): Promise<string | undefined> {
  const rows = await $.session.messages();
  return rows.findLast((row) => row.role === "user" && row.text.startsWith(SUMMARY_OPENING))?.text;
}

/** The `text` of the orient verb's data; anything else is a failure. */
function briefingText(data: unknown): string {
  if (
    typeof data === "object" &&
    data !== null &&
    "text" in data &&
    typeof data.text === "string"
  ) {
    return data.text;
  }
  throw new Error("qsm-memory orient answered no text");
}

/** Why a hook failed, in words: the thrown message (it names the verb, its exit and its stderr or
 * outcome code), or for a timeout the budget it outran, which the engine gives no message for. */
function causeOf(error: Caught["error"]): string {
  return error.message ?? `${error.kind}: ran past its ${error.budget} ms budget`;
}

/** What every `.catch` here does before the event goes on: a toast and a log for the person. The
 * toast keeps the cause up to 240 characters, the log all of it. */
function failed($: EngineInterface, event: string, error: Caught["error"]): void {
  const cause = causeOf(error);
  $.ui.toast(`qsm-memory ERROR: ${event}: ${cause.slice(0, 240)}`);
  $.ui.log(`${event} failed open (${error.kind}): ${cause}`);
}

/** Saves this session and any an earlier end missed, in a detached child. */
function saveCatchUp($: EngineInterface) {
  return $.memory.save({ catchUp: true, detach: true });
}

export function register(on: On): void {
  // Adds $.memory: one method per qsm-memory verb, generated by
  // lib/generate-noun.ts. Never hand-edit noun.generated.ts or types/index.d.ts.
  registerNoun(on);

  on("session.start", async ($, e, next) => {
    briefingOwed = true;
    // doctor fails when Claude Code is set to delete transcripts, and the catch below toasts it
    // every session until it is fixed: a deleted transcript never comes back.
    await Promise.all([saveCatchUp($), $.memory.pack({ detach: true }), $.memory.doctor()]);
    return next(e);
  }).catch(($, e, next) => {
    failed($, "session.start", next.error);
    return next(e);
  });

  on("session.end", async ($, e, next) => {
    briefingOwed = e.reason === "clear";
    await saveCatchUp($);
    return next(e);
  }).catch(($, e, next) => {
    failed($, "session.end", next.error);
    return next(e);
  });

  on("prompt.submit", async ($, e, next) => {
    const summary = await latestSummary($);
    if (!briefingOwed && summary === briefedSummary) {
      return next(e);
    }
    briefingOwed = false;
    briefedSummary = summary;
    const briefing = briefingText(await $.memory.orient({ cwd: await $.session.cwd() }));
    return next({ ...e, context: [...(e.context ?? []), briefing] });
  }).catch(($, e, next) => {
    failed($, "prompt.submit", next.error);
    return next(e);
  });
}
