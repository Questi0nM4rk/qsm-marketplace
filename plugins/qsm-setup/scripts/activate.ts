#!/usr/bin/env bun
// The always-loaded instructions every agent on this machine reads: CLAUDE.md, the three rules and
// the output style, each written into the user's Claude home as one marked area qsm-setup owns.

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, resolve } from "node:path";
import {
  type Activation,
  type ActivationContext,
  type ActivationState,
  activationMain,
  type InstallResult,
  type Step,
} from "../../../lib/install-contract.ts";

const NAME = "instructions";
const SRC = resolve(import.meta.dir, "../instructions");
/** The marker lines around the area qsm-setup owns in every file it generates. */
const BEGIN =
  "<!-- qsm-setup-begin: generated by qsm-setup, which owns and rewrites everything up to qsm-setup-end and any frontmatter above it; write your own text outside this area -->";
const END =
  "<!-- qsm-setup-end: generated area ends; text outside it is yours and never touched -->";
/**
 * Recognised by prefix, so the older bare `<!-- qsm-setup-begin -->` reads as marked too. A marker
 * may be indented, and the text after its `-->` is not part of it.
 */
const BEGIN_LINE = /^[ \t]*<!-- qsm-setup-begin\b.*?-->/gm;
const END_LINE = /^[ \t]*<!-- qsm-setup-end\b.*?-->/gm;
/** The block qsm-essentials wrote before setup owned the instructions; removed before writing. */
const OLD_BEGIN = "<!-- qsm-essentials-begin -->";
const OLD_END = "<!-- qsm-essentials-end -->";
const FRONTMATTER = /^---\r?\n[\s\S]*?\r?\n---\r?\n/;
const STYLE = "qsm";
/** Every file the activation generates, by its path under the plugin's instructions and the home. */
const GENERATED = [
  "CLAUDE.md",
  "rules/implementation.md",
  "rules/context.md",
  "rules/git.md",
  "output-styles/qsm.md",
];

function claudeHome(env: ActivationContext["env"]): string {
  return env.CLAUDE_CONFIG_DIR ?? resolve(env.HOME ?? homedir(), ".claude");
}

export type InstructionsChoice = "replace" | "overwrite" | "skip";

/** The text without the older qsm-essentials block, or unchanged when it has none. */
function withoutOldBlock(text: string): string {
  const start = text.indexOf(OLD_BEGIN);
  const end = text.indexOf(OLD_END);
  if (start === -1 || end < start) {
    return text;
  }
  return (text.slice(0, start) + text.slice(end + OLD_END.length).replace(/^\n/, "")).replace(
    /\n{3,}/g,
    "\n\n",
  );
}

/** The leading YAML frontmatter ("" when none) and the rest. */
function splitFrontmatter(text: string): { front: string; body: string } {
  const front = FRONTMATTER.exec(text)?.[0] ?? "";
  return { front, body: text.slice(front.length) };
}

/** Where the marked area starts and ends (past the end line), or null with no marker at all. */
function markedArea(text: string): { start: number; end: number } | null {
  const begins = [...text.matchAll(BEGIN_LINE)];
  const ends = [...text.matchAll(END_LINE)];
  if (begins.length === 0 && ends.length === 0) {
    return null;
  }
  const [begin] = begins;
  const [end] = ends;
  if (begins.length !== 1 || ends.length !== 1 || begin === undefined || end === undefined) {
    throw new Error(
      `broken qsm-setup markers: ${begins.length} begin and ${ends.length} end lines, expected one of each`,
    );
  }
  if (end.index < begin.index) {
    throw new Error("broken qsm-setup markers: the end line comes before the begin line");
  }
  return { start: begin.index, end: end.index + end[0].length };
}

/**
 * One generated file after activation: the source's frontmatter first, then the source's body
 * between the markers. `replace` keeps every byte outside the markers except the frontmatter,
 * which is qsm's (`frontReplaced` says it differed); a file without markers is replaced whole when
 * `recognised` says qsm wrote it, else kept whole, its own frontmatter too, with the area after it.
 * Throws on broken markers.
 */
function mergeBlock(
  current: string | null,
  source: string,
  choice: Exclude<InstructionsChoice, "skip">,
  recognised: (text: string) => boolean,
): { text: string; kept: boolean; frontReplaced: boolean } {
  const { front, body } = splitFrontmatter(source);
  const area = `${BEGIN}\n${body.trim()}\n${END}\n`;
  const existing = current === null ? "" : withoutOldBlock(current);
  if (choice === "overwrite" || existing.trim() === "") {
    return { text: front + area, kept: false, frontReplaced: false };
  }
  const { front: oldFront, body: outside } = splitFrontmatter(existing);
  const found = markedArea(outside);
  if (found !== null) {
    const after = outside.slice(found.end).replace(/^[ \t]*\r?\n/, "");
    return {
      text: front + outside.slice(0, found.start) + area + after,
      kept: false,
      frontReplaced: front !== "" && oldFront !== front,
    };
  }
  if (recognised(existing)) {
    return { text: front + area, kept: false, frontReplaced: false };
  }
  const own = oldFront === "" ? front : "";
  return { text: `${own}${existing.trimEnd()}\n\n${area}`, kept: true, frontReplaced: false };
}

/** settings.json with outputStyle set. Everything else untouched. */
export function selectStyle(existing: string | null): string {
  const settings: Record<string, unknown> = existing ? JSON.parse(existing) : {};
  settings.outputStyle = STYLE;
  return `${JSON.stringify(settings, null, 2)}\n`;
}

interface Target {
  readonly path: string;
  readonly content: string;
  /** The person's unmarked text was kept above the generated area. */
  readonly kept: boolean;
  /** The frontmatter in the file was not qsm's and has been replaced. */
  readonly frontReplaced: boolean;
}

/** What every `qsm-setup activate:` commit in the home wrote to `rel`, newest first. */
function activatedVersions(home: string, env: ActivationContext["env"], rel: string): string[] {
  if (!existsSync(resolve(home, ".git"))) {
    return [];
  }
  try {
    const shas = git(home, env, [
      "log",
      "--format=%H",
      "--grep=^qsm-setup activate: ",
      "--",
      rel,
    ]).split("\n");
    return shas
      .filter((sha) => sha !== "")
      .flatMap((sha) => {
        try {
          return [git(home, env, ["show", `${sha}:${rel}`])];
        } catch {
          return []; // a commit that removed the file
        }
      });
  } catch {
    return [];
  }
}

/** Every file the choice writes, with its content; throws naming the file on broken markers. */
function targets(
  home: string,
  env: ActivationContext["env"],
  choice: Exclude<InstructionsChoice, "skip">,
): Target[] {
  const existing = (path: string) => (existsSync(path) ? readFileSync(path, "utf8") : null);
  const generated = GENERATED.map((rel): Target => {
    const path = resolve(home, rel);
    const source = readFileSync(resolve(SRC, rel), "utf8");
    const recognised = (text: string) =>
      text === source || activatedVersions(home, env, rel).includes(text);
    try {
      const { text, kept, frontReplaced } = mergeBlock(existing(path), source, choice, recognised);
      return { path, content: text, kept, frontReplaced };
    } catch (e) {
      throw new Error(`${path}: ${e instanceof Error ? e.message : String(e)}`, { cause: e });
    }
  });
  const settings = resolve(home, "settings.json");
  return [
    ...generated,
    { path: settings, content: selectStyle(existing(settings)), kept: false, frontReplaced: false },
  ];
}

/** What the Claude home never keeps in history: secrets, caches, logs, and per-session state. */
const GITIGNORE = `.credentials.json *.bak *.lock *.log .last-* history.jsonl stats-cache.json
*-cache.json policy-limits*.json remote-settings.json daemon* projects/ file-history/ session-env/
shell-snapshots/ sessions/ debug/ paste-cache/ cache/ backups/ chrome/ jobs/ state/ tasks/ teams/
feedback/ security/ usage-data/ cc-review-memory/ plugins/cache/ plugins/marketplaces/
plugins/repos/ plugins/data/`.split(/\s+/);

const GIT_BEFORE = "git-before";
const GIT_AFTER = "git-after";

/** Runs git in the Claude home, without the GIT_* variables of whatever repository called us. */
function git(home: string, env: ActivationContext["env"], args: string[]): string {
  const clean = Object.fromEntries(
    Object.entries({ ...process.env, ...env }).filter(
      ([k]) => !k.startsWith("GIT_") || k.startsWith("GIT_AUTHOR") || k.startsWith("GIT_COMMITTER"),
    ),
  );
  const run = spawnSync("git", args, { cwd: home, env: clean, encoding: "utf8" });
  if (run.error || run.status !== 0) {
    const cause = run.error?.message ?? (run.stderr.trim() || `exit ${run.status}`);
    throw new Error(`git ${args.join(" ")}: ${cause}`);
  }
  return run.stdout;
}

/** The .gitignore with the lines it lacks appended; the person's own lines stay. */
function completedGitignore(current: string | null): string | null {
  const have = new Set((current ?? "").split("\n").map((l) => l.trim()));
  const missing = GITIGNORE.filter((l) => !have.has(l));
  if (missing.length === 0) {
    return null;
  }
  const kept = current === null || current === "" ? "" : `${current.replace(/\n*$/, "")}\n`;
  return `${kept}${missing.join("\n")}\n`;
}

function failed(name: string, e: unknown): Step {
  return { name, status: "error", detail: e instanceof Error ? e.message : String(e) };
}

/** First step: the Claude home is a local repository with its .gitignore and a clean tree. */
export function gitBeforeStep(ctx: ActivationContext): Step {
  const home = claudeHome(ctx.env);
  const ignorePath = resolve(home, ".gitignore");
  const isRepo = existsSync(resolve(home, ".git"));
  const ignore = completedGitignore(
    existsSync(ignorePath) ? readFileSync(ignorePath, "utf8") : null,
  );
  try {
    if (ctx.dryRun) {
      const plan = [
        ...(isRepo ? [] : ["git init"]),
        ...(ignore === null ? [] : ["complete .gitignore"]),
        "commit anything uncommitted as 'before qsm-setup activate'",
      ];
      return { name: GIT_BEFORE, status: "skipped", detail: `would ${plan.join(", ")} in ${home}` };
    }
    mkdirSync(home, { recursive: true });
    if (!isRepo) {
      git(home, ctx.env, ["init", "--quiet"]);
    }
    if (ignore !== null) {
      writeFileSync(ignorePath, ignore);
    }
    if (git(home, ctx.env, ["status", "--porcelain"]).trim() === "") {
      return {
        name: GIT_BEFORE,
        status: "already",
        detail: `${home} is a repository with nothing uncommitted`,
      };
    }
    git(home, ctx.env, ["add", "-A"]);
    git(home, ctx.env, ["commit", "--quiet", "-m", "before qsm-setup activate"]);
    return {
      name: GIT_BEFORE,
      status: "installed",
      detail: `committed ${home} as 'before qsm-setup activate'`,
    };
  } catch (e) {
    return failed(GIT_BEFORE, e);
  }
}

/** Last step: commit exactly what activation wrote. */
function gitAfterStep(ctx: ActivationContext, home: string, written: string[]): Step {
  if (written.length === 0) {
    return { name: GIT_AFTER, status: "already", detail: "nothing written, nothing to commit" };
  }
  const names = written.join(", ");
  if (ctx.dryRun) {
    return {
      name: GIT_AFTER,
      status: "skipped",
      detail: `would commit ${names} as 'qsm-setup activate: ${names}'`,
    };
  }
  try {
    git(home, ctx.env, ["add", "--", ...written]);
    git(home, ctx.env, [
      "commit",
      "--quiet",
      "-m",
      `qsm-setup activate: ${names}`,
      "--",
      ...written,
    ]);
    return { name: GIT_AFTER, status: "installed", detail: `committed ${names}` };
  } catch (e) {
    return failed(GIT_AFTER, e);
  }
}

/** The whole managed write, taken or not taken as one. */
export function instructionsStep(ctx: ActivationContext): Step {
  return writeInstructions(ctx).step;
}

function writeInstructions(ctx: ActivationContext): { step: Step; written: string[] } {
  const home = claudeHome(ctx.env);
  const choice = ctx.choices.instructions as InstructionsChoice;
  if (choice === "skip") {
    return {
      step: {
        name: NAME,
        status: "skipped",
        detail:
          "--instructions skip: the generated files, settings.json and the history are left alone",
      },
      written: [],
    };
  }
  let all: Target[];
  try {
    all = targets(home, ctx.env, choice);
  } catch (e) {
    return { step: failed(NAME, e), written: [] };
  }
  const changes = all.filter(
    (t) => !existsSync(t.path) || readFileSync(t.path, "utf8") !== t.content,
  );
  const written = changes.map((t) => t.path.slice(home.length + 1));
  if (changes.length === 0) {
    return {
      step: {
        name: NAME,
        status: "already",
        detail: `instructions in ${home} already match the plugin`,
      },
      written,
    };
  }
  const kept = changes.filter((t) => t.kept).map((t) => t.path.slice(home.length + 1));
  const replaced = changes.filter((t) => t.frontReplaced).map((t) => t.path.slice(home.length + 1));
  const keptNote =
    (kept.length === 0
      ? ""
      : `; kept your text above the qsm-setup area in ${kept.join(", ")} (if that text is an old generated copy, it now repeats the area: delete it)`) +
    (replaced.length === 0
      ? ""
      : `; replaced the frontmatter of ${replaced.join(", ")} (qsm-setup owns it)`);
  const names = written.join(", ");
  if (ctx.dryRun) {
    return {
      step: { name: NAME, status: "skipped", detail: `would write ${names}${keptNote}` },
      written,
    };
  }
  for (const t of changes) {
    mkdirSync(dirname(t.path), { recursive: true });
    writeFileSync(t.path, t.content);
  }
  return {
    step: { name: NAME, status: "installed", detail: `wrote ${names}${keptNote}` },
    written,
  };
}

/**
 * Absent without the rules file; differs when any managed file is not what activation writes.
 * Throws, naming the file, on broken markers: the status call reports that cause.
 */
function instructionsState(env: ActivationContext["env"]): ActivationState {
  const home = claudeHome(env);
  if (!existsSync(resolve(home, "rules/implementation.md"))) {
    return "absent";
  }
  const stale = targets(home, env, "replace").some(
    (t) => !existsSync(t.path) || readFileSync(t.path, "utf8") !== t.content,
  );
  return stale ? "differs" : "activated";
}

export const activation: Activation = {
  status: instructionsState,
  options: [
    {
      name: "instructions",
      values: ["replace", "overwrite", "skip"],
      description:
        "what happens to each generated file (CLAUDE.md, the rules, the output style): only our marked area replaced and everything outside it kept (the default), the whole file overwritten with the area (only when asked), or every file left alone",
    },
  ],
  activate: (ctx): InstallResult => {
    const home = claudeHome(ctx.env);
    if (ctx.choices.instructions === "skip") {
      const { step } = writeInstructions(ctx);
      return { tool: "qsm-setup", status: step.status, detail: step.detail, steps: [step] };
    }
    const before = gitBeforeStep(ctx);
    if (before.status === "error") {
      return { tool: "qsm-setup", status: "error", detail: before.detail, steps: [before] };
    }
    const { step, written } = writeInstructions(ctx);
    const after =
      step.status === "installed"
        ? gitAfterStep(ctx, home, written)
        : gitAfterStep(ctx, home, ctx.dryRun ? written : []);
    const steps = [before, step, after];
    const status = steps.find((s) => s.status === "error")?.status ?? step.status;
    return {
      tool: "qsm-setup",
      status,
      detail: steps.map((s) => `${s.name}: ${s.detail}`).join("; "),
      steps,
    };
  },
};

if (import.meta.main) {
  process.exit(await activationMain(activation));
}
