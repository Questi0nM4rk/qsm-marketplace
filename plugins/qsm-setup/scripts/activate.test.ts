import { describe, expect, test } from "bun:test";
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { YAML } from "bun";
import { sandboxDir, writeIn } from "../../../lib/fixtures/sandbox.ts";
import { bunActivationReader } from "../lib/run-installers.ts";
import { activation, instructionsStep } from "./activate.ts";

/** The activation's one step is the whole result. */
function context(home: string, claudeHome: string, instructions = "replace") {
  return {
    dryRun: false,
    env: {
      HOME: home,
      CLAUDE_CONFIG_DIR: claudeHome,
      GIT_AUTHOR_NAME: "t",
      GIT_AUTHOR_EMAIL: "t@t",
      GIT_COMMITTER_NAME: "t",
      GIT_COMMITTER_EMAIL: "t@t",
      GIT_CONFIG_GLOBAL: "/dev/null",
    },
    choices: { instructions },
  };
}
const install = activation.activate;

function sandbox(): { home: string; claudeHome: string } {
  return {
    home: sandboxDir("qsm-home-"),
    claudeHome: sandboxDir("qsm-claude-"),
  };
}

describe("the managed write as one step", () => {
  test("the whole write is one step between the two git steps", async () => {
    const { home, claudeHome } = sandbox();

    const result = await install(context(home, claudeHome));

    expect(result.tool).toBe("qsm-setup");
    expect(result.steps?.map((s) => s.name)).toEqual(["git-before", "instructions", "git-after"]);
    expect(result.steps?.[1]).toMatchObject({ name: "instructions", status: "installed" });
    for (const name of [
      "CLAUDE.md",
      "rules/implementation.md",
      "rules/context.md",
      "rules/git.md",
      "output-styles/qsm.md",
      "settings.json",
    ]) {
      expect(result.detail).toContain(name);
    }
  });

  test("running it again with nothing changed is already", async () => {
    const { home, claudeHome } = sandbox();

    await install(context(home, claudeHome));
    const again = await install(context(home, claudeHome));

    expect(again.status).toBe("already");
    expect(again.steps?.[1]).toMatchObject({ name: "instructions", status: "already" });
  });

  test("a dry run writes nothing", async () => {
    const { home, claudeHome } = sandbox();

    const result = await install({ ...context(home, claudeHome), dryRun: true });

    expect(result.status).toBe("skipped");
    expect(existsSync(resolve(claudeHome, "CLAUDE.md"))).toBe(false);
  });

  test("the step itself names what a dry run would change", () => {
    const { home, claudeHome } = sandbox();

    const step = instructionsStep({ ...context(home, claudeHome), dryRun: true });

    expect(step.status).toBe("skipped");
    expect(step.detail).toContain("write CLAUDE.md");
    expect(existsSync(resolve(claudeHome, "CLAUDE.md"))).toBe(false);
  });
});

function log(dir: string): string[] {
  const out = spawnSync("git", ["log", "--format=%s"], { cwd: dir, encoding: "utf8" }).stdout;
  return out.trim().split("\n");
}

describe("history of the Claude home", () => {
  test("a home that is not a repo ends with a repo, the ignore file and two commits; again adds none", async () => {
    const { home, claudeHome } = sandbox();
    writeFileSync(join(claudeHome, "mine.txt"), "x");
    writeFileSync(join(claudeHome, ".gitignore"), "my-own/\n");

    await install(context(home, claudeHome));
    const first = log(claudeHome);
    await install(context(home, claudeHome));

    expect(first).toHaveLength(2);
    expect(first[1]).toBe("before qsm-setup activate");
    expect(first[0]).toStartWith("qsm-setup activate: ");
    expect(log(claudeHome)).toEqual(first);
    const ignore = readFileSync(join(claudeHome, ".gitignore"), "utf8");
    expect(ignore).toStartWith("my-own/\n");
    expect(ignore).toContain("\nprojects/\n");
  });

  test("a dry run names the git steps and writes nothing", async () => {
    const { home, claudeHome } = sandbox();

    const result = await install({ ...context(home, claudeHome), dryRun: true });

    expect(result.steps?.[0]?.detail).toContain("git init");
    expect(result.steps?.[2]?.detail).toContain("would commit");
    expect(existsSync(join(claudeHome, ".git"))).toBe(false);
    expect(existsSync(join(claudeHome, ".gitignore"))).toBe(false);
  });

  test("a git failure is an error naming the cause, and nothing is written", async () => {
    const { home, claudeHome } = sandbox();
    writeFileSync(join(claudeHome, ".git"), "not a repository");

    const result = await install(context(home, claudeHome));

    expect(result.status).toBe("error");
    expect(result.detail).toContain("git status");
    expect(existsSync(join(claudeHome, "CLAUDE.md"))).toBe(false);
  });
});

const GENERATED = [
  "CLAUDE.md",
  "rules/implementation.md",
  "rules/context.md",
  "rules/git.md",
  "output-styles/qsm.md",
];
const BEGIN = /^<!-- qsm-setup-begin: generated by qsm-setup.*-->$/m;
const END = /^<!-- qsm-setup-end.*-->$/m;
const source = (rel: string) =>
  readFileSync(resolve(import.meta.dir, "../instructions", rel), "utf8");
const read = (dir: string, rel: string) => readFileSync(join(dir, rel), "utf8");
const snapshot = (dir: string) =>
  [...GENERATED, "settings.json"].map((rel) => [rel, read(dir, rel)]);

describe("every generated file is one marked area qsm-setup owns", () => {
  test("a fresh home gets every file marked, and the style's frontmatter stays first and parses", async () => {
    const { home, claudeHome } = sandbox();

    await install(context(home, claudeHome));

    for (const rel of GENERATED) {
      const text = read(claudeHome, rel);
      expect(text).toMatch(BEGIN);
      expect(text).toMatch(END);
      expect(text.match(/qsm-setup-begin/g)).toHaveLength(1);
    }
    const style = read(claudeHome, "output-styles/qsm.md");
    const front = /^---\n([\s\S]*?)\n---\n/.exec(style);
    expect(front).not.toBeNull();
    expect(YAML.parse(front?.[1] ?? "")).toMatchObject({ name: "qsm" });
    expect(style.slice(front?.[0].length)).toMatch(/^<!-- qsm-setup-begin/);
  });

  test("a second run writes nothing and every file stays byte for byte", async () => {
    const { home, claudeHome } = sandbox();
    writeIn(claudeHome, "rules/git.md", "my own git notes\n");
    await install(context(home, claudeHome));
    const first = snapshot(claudeHome);

    const again = await install(context(home, claudeHome));

    expect(again.status).toBe("already");
    expect(snapshot(claudeHome)).toEqual(first);
  });

  test("the person's text above and below the area survives a replace byte for byte", async () => {
    const { home, claudeHome } = sandbox();
    await install(context(home, claudeHome));
    const rule = read(claudeHome, "rules/context.md");
    const style = read(claudeHome, "output-styles/qsm.md");
    const front = /^---\n[\s\S]*?\n---\n/.exec(style)?.[0] ?? "";
    const stale = (text: string) => text.replace(END, "stale line\n$&");
    writeIn(claudeHome, "rules/context.md", `# mine above\n\n${stale(rule)}\nmine below\n`);
    writeIn(
      claudeHome,
      "output-styles/qsm.md",
      `${front}Answer in Czech.\n\n${stale(style.slice(front.length))}\nSign off with my name.\n`,
    );

    await install(context(home, claudeHome));

    expect(read(claudeHome, "rules/context.md")).toBe(`# mine above\n\n${rule}\nmine below\n`);
    expect(read(claudeHome, "output-styles/qsm.md")).toBe(
      `${front}Answer in Czech.\n\n${style.slice(front.length)}\nSign off with my name.\n`,
    );
  });
});

describe("a file without markers", () => {
  test("an old whole-file install, committed by a past activation or equal to the source, becomes the area alone", async () => {
    const { home, claudeHome } = sandbox();
    const { env } = context(home, claudeHome);
    const inHome = (...args: string[]) => spawnSync("git", args, { cwd: claudeHome, env });
    inHome("init", "--quiet");
    writeIn(claudeHome, "rules/git.md", "# Git rule\n\nan older generated version\n");
    inHome("add", "-A");
    inHome("commit", "--quiet", "-m", "qsm-setup activate: rules/git.md");
    writeIn(claudeHome, "rules/context.md", source("rules/context.md"));

    const result = await install(context(home, claudeHome));

    for (const rel of ["rules/git.md", "rules/context.md"]) {
      const text = read(claudeHome, rel);
      expect(text).toMatch(/^<!-- qsm-setup-begin/);
      expect(text).not.toContain("an older generated version");
      expect(text.match(/^# /gm)).toHaveLength(1);
    }
    expect(result.detail).not.toContain("kept your text");
  });

  test("unmarked text qsm did not write is kept above the area and named in the result", async () => {
    const { home, claudeHome } = sandbox();
    writeIn(claudeHome, "rules/implementation.md", "# my own rules\n\nalways tdd\n");

    const result = await install(context(home, claudeHome));

    const text = read(claudeHome, "rules/implementation.md");
    expect(text).toStartWith("# my own rules\n\nalways tdd\n\n<!-- qsm-setup-begin");
    expect(result.detail).toContain(
      "kept your text above the qsm-setup area in rules/implementation.md",
    );
  });
});

describe("a file with older or broken markers", () => {
  test.each([
    ["a begin without an end", "<!-- qsm-setup-begin -->\nhalf\n", "1 begin and 0 end"],
    [
      "two begins",
      "<!-- qsm-setup-begin -->\n<!-- qsm-setup-begin -->\nx\n<!-- qsm-setup-end -->\n",
      "2 begin and 1 end",
    ],
    ["an end before the begin", "<!-- qsm-setup-end -->\n<!-- qsm-setup-begin -->\n", "before"],
  ])("%s fails loud naming the file, and nothing is written", async (_, broken, fault) => {
    const { home, claudeHome } = sandbox();
    writeIn(claudeHome, "rules/git.md", broken);

    const result = await install(context(home, claudeHome));

    expect(result.status).toBe("error");
    expect(result.detail).toContain(
      `${join(claudeHome, "rules/git.md")}: broken qsm-setup markers`,
    );
    expect(result.detail).toContain(fault);
    expect(read(claudeHome, "rules/git.md")).toBe(broken);
    expect(existsSync(join(claudeHome, "CLAUDE.md"))).toBe(false);
  });

  test("a CLAUDE.md marked by the older bare markers is rewritten in place, not doubled", async () => {
    const { home, claudeHome } = sandbox();
    writeIn(
      claudeHome,
      "CLAUDE.md",
      "# mine\n\n<!-- qsm-setup-begin -->\nold\n<!-- qsm-setup-end -->\n",
    );

    await install(context(home, claudeHome));

    const text = read(claudeHome, "CLAUDE.md");
    expect(text).toStartWith("# mine\n\n<!-- qsm-setup-begin: generated by qsm-setup");
    expect(text).not.toContain("\nold\n");
    expect(text.match(/qsm-setup-begin/g)).toHaveLength(1);
  });

  test("the block qsm-essentials wrote is removed and one qsm-setup area follows the person's text", async () => {
    const { home, claudeHome } = sandbox();
    writeIn(
      claudeHome,
      "CLAUDE.md",
      "# mine\n\n<!-- qsm-essentials-begin -->\nold\n<!-- qsm-essentials-end -->\n",
    );

    await install(context(home, claudeHome));

    const text = read(claudeHome, "CLAUDE.md");
    expect(text).not.toContain("qsm-essentials-begin");
    expect(text).toStartWith("# mine\n\n<!-- qsm-setup-begin");
  });
});

const front = (text: string) => /^---\r?\n[\s\S]*?\r?\n---\r?\n/.exec(text)?.[0] ?? "";

describe("the person's own text and the generated area meet at their edges", () => {
  test("an unmarked style with the person's own frontmatter is kept whole, frontmatter included", async () => {
    const { home, claudeHome } = sandbox();
    const mine = "---\ndescription: MY OWN STYLE\n---\nAnswer in Czech.\n";
    writeIn(claudeHome, "output-styles/qsm.md", mine);

    const result = await install(context(home, claudeHome));

    const text = read(claudeHome, "output-styles/qsm.md");
    expect(text).toStartWith(`${mine}\n<!-- qsm-setup-begin`);
    expect(text.match(/^---$/gm)).toHaveLength(2);
    expect(result.detail).toContain(
      "kept your text above the qsm-setup area in output-styles/qsm.md",
    );
  });

  test("in a marked style the frontmatter is qsm's: the marker says so, an edit is replaced and the result names it", async () => {
    const { home, claudeHome } = sandbox();
    await install(context(home, claudeHome));
    const style = read(claudeHome, "output-styles/qsm.md");
    expect(style).toMatch(/qsm-setup-begin:[^\n]*frontmatter/);
    writeIn(
      claudeHome,
      "output-styles/qsm.md",
      style.replace("\n---\n", "\nkeep-coding-instructions: true\n---\n"),
    );

    const result = await install(context(home, claudeHome));

    expect(read(claudeHome, "output-styles/qsm.md")).toBe(style);
    expect(result.detail).toContain("replaced the frontmatter of output-styles/qsm.md");
  });

  test("a style written with CRLF line endings ends with one frontmatter and one area", async () => {
    const { home, claudeHome } = sandbox();
    await install(context(home, claudeHome));
    const style = read(claudeHome, "output-styles/qsm.md");
    writeIn(claudeHome, "output-styles/qsm.md", style.replace(/\n/g, "\r\n"));

    await install(context(home, claudeHome));

    const text = read(claudeHome, "output-styles/qsm.md");
    expect(text.match(/^---\r?$/gm)).toHaveLength(2);
    expect(text.match(/^name: qsm/gm)).toHaveLength(1);
    expect(text.match(/qsm-setup-begin/g)).toHaveLength(1);
    expect(front(text)).toBe(front(style));
  });
});

describe("line endings and marker shape", () => {
  test("a CRLF file keeps its text below the area with no extra blank line, and is stable", async () => {
    const { home, claudeHome } = sandbox();
    await install(context(home, claudeHome));
    const rule = read(claudeHome, "rules/git.md");
    writeIn(
      claudeHome,
      "rules/git.md",
      `above\r\n\r\n${rule.replace(/\n/g, "\r\n")}\r\nmine below\r\n`,
    );

    await install(context(home, claudeHome));
    const first = read(claudeHome, "rules/git.md");
    const again = await install(context(home, claudeHome));

    expect(first).toBe(`above\r\n\r\n${rule}\r\nmine below\r\n`);
    expect(again.status).toBe("already");
  });

  test("an indented marker line, or text after the end marker, is still a marker and the text stays", async () => {
    const { home, claudeHome } = sandbox();
    writeIn(
      claudeHome,
      "rules/git.md",
      "mine\n  <!-- qsm-setup-begin -->\nold\n\t<!-- qsm-setup-end --> and more\nbelow\n",
    );

    await install(context(home, claudeHome));

    const text = read(claudeHome, "rules/git.md");
    expect(text).toStartWith("mine\n<!-- qsm-setup-begin: generated");
    expect(text.match(/qsm-setup-begin/g)).toHaveLength(1);
    expect(text).not.toContain("\nold\n");
    expect(text).toEndWith("-->\n and more\nbelow\n");
  });
});

describe("an old generated file the person kept", () => {
  test("a file equal to any earlier qsm-setup activate commit, not only the newest, becomes the area alone", async () => {
    const { home, claudeHome } = sandbox();
    const { env } = context(home, claudeHome);
    const inHome = (...args: string[]) => spawnSync("git", args, { cwd: claudeHome, env });
    inHome("init", "--quiet");
    const commitVersion = (content: string) => {
      writeIn(claudeHome, "rules/git.md", content);
      inHome("add", "-A");
      inHome("commit", "--quiet", "-m", "qsm-setup activate: rules/git.md");
    };
    commitVersion("# Git rule\n\nthe first generated version\n");
    commitVersion("# Git rule\n\nthe second generated version\n");
    writeIn(claudeHome, "rules/git.md", "# Git rule\n\nthe first generated version\n");

    const result = await install(context(home, claudeHome));

    const text = read(claudeHome, "rules/git.md");
    expect(text).toStartWith("<!-- qsm-setup-begin");
    expect(text).not.toContain("generated version");
    expect(result.detail).not.toContain("kept your text");
  });

  test("a kept text that may be an old generated copy is named as one that now repeats the area", async () => {
    const { home, claudeHome } = sandbox();
    writeIn(claudeHome, "rules/git.md", "# Git rule\n\na lightly edited old copy\n");

    const result = await install(context(home, claudeHome));

    expect(result.detail).toContain("old generated copy");
  });
});

describe("overwrite, skip and a broken marker seen by doctor", () => {
  test("overwrite leaves only the area, and the style its frontmatter and the area", async () => {
    const { home, claudeHome } = sandbox();
    writeIn(claudeHome, "CLAUDE.md", "# mine\n");
    writeIn(claudeHome, "output-styles/qsm.md", "mine\n");

    await install(context(home, claudeHome, "overwrite"));

    expect(read(claudeHome, "CLAUDE.md")).toStartWith("<!-- qsm-setup-begin");
    expect(read(claudeHome, "output-styles/qsm.md")).toMatch(
      /^---\nname: qsm\n[\s\S]*?\n---\n<!-- qsm-setup-begin/,
    );
  });

  test("skip leaves the Claude home alone: no repository, no ignore file, no commit, no file", async () => {
    const { home, claudeHome } = sandbox();
    writeIn(claudeHome, "CLAUDE.md", "# mine\n");

    const result = await install(context(home, claudeHome, "skip"));

    expect(result.status).toBe("skipped");
    expect(result.steps).toMatchObject([{ name: "instructions", status: "skipped" }]);
    expect(read(claudeHome, "CLAUDE.md")).toBe("# mine\n");
    expect(existsSync(join(claudeHome, "rules/context.md"))).toBe(false);
    expect(existsSync(join(claudeHome, ".git"))).toBe(false);
    expect(existsSync(join(claudeHome, ".gitignore"))).toBe(false);
  });

  test("doctor's reader gets the broken-marker cause, not a bare 'differs'", () => {
    const { claudeHome } = sandbox();
    writeIn(claudeHome, "rules/implementation.md", "x\n");
    writeIn(claudeHome, "rules/git.md", "<!-- qsm-setup-begin -->\nhalf\n");
    const was = process.env.CLAUDE_CONFIG_DIR;
    process.env.CLAUDE_CONFIG_DIR = claudeHome;
    try {
      const report = bunActivationReader(resolve(import.meta.dir, "activate.ts"));

      expect(typeof report).toBe("string");
      expect(report).toContain("broken qsm-setup markers");
      expect(report).toContain(join(claudeHome, "rules/git.md"));
    } finally {
      if (was === undefined) {
        delete process.env.CLAUDE_CONFIG_DIR;
      } else {
        process.env.CLAUDE_CONFIG_DIR = was;
      }
    }
  });
});
